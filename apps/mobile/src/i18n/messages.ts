/**
 * Resolves mobile-specific copy, then reuses the desktop/client translation catalog.
 * @param language Resolved language for this device.
 * @param source App-owned interface text; unknown copy deliberately retains its original spelling.
 * @returns Localized interface copy, without rewriting agent output or remote error data.
 */
export function translateMobileText(language: UiLanguage, source: string): string {
  return language === "zh-CN" ? (mobileCopy[source] ?? translateUiText(language, source)) : source;
}
